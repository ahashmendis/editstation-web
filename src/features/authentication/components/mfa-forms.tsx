"use client";

import { useActionState, useState, useTransition } from "react";

import { Button } from "@/components/ui/button";

import {
  startTotpEnrollmentAction,
  verifyTotpAction,
  verifyTotpEnrollmentAction,
  type EnrollmentState,
} from "../mfa-actions";
import { initialFormState } from "../schemas";
import { Field, FormMessage } from "./form-parts";

function CodeField({ state }: { state: Parameters<typeof Field>[0]["state"] }) {
  return (
    <Field
      name="code"
      label="6-digit code"
      inputMode="numeric"
      autoComplete="one-time-code"
      state={state}
      required
    />
  );
}

export function MfaEnrollForm() {
  const [enrollment, setEnrollment] = useState<EnrollmentState | null>(null);
  const [starting, startTransition] = useTransition();
  const [state, action, pending] = useActionState(verifyTotpEnrollmentAction, initialFormState);

  if (!enrollment?.factorId) {
    return (
      <div className="grid gap-4">
        {enrollment ? <FormMessage state={enrollment} /> : null}
        <p className="text-muted-foreground text-sm">
          Admin accounts must use an authenticator app (for example Google Authenticator, 1Password
          or Authy) in addition to a password.
        </p>
        <Button
          disabled={starting}
          onClick={() =>
            startTransition(async () => setEnrollment(await startTotpEnrollmentAction()))
          }
        >
          {starting ? "Preparing…" : "Set up authenticator app"}
        </Button>
      </div>
    );
  }

  return (
    <form action={action} className="grid gap-4" noValidate>
      <FormMessage state={state} />
      <p className="text-sm">Scan this QR code with your authenticator app:</p>
      {/* QR is an SVG data URL generated by our own Supabase Auth server. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={enrollment.qrCode}
        alt="Authenticator QR code"
        className="size-44 rounded-md bg-white p-2"
      />
      <details className="text-sm">
        <summary className="cursor-pointer">Can&apos;t scan? Enter this key instead</summary>
        <code className="mt-2 block break-all">{enrollment.secret}</code>
      </details>
      <input type="hidden" name="factorId" value={enrollment.factorId} />
      <CodeField state={state} />
      <Button type="submit" disabled={pending}>
        {pending ? "Verifying…" : "Verify and continue"}
      </Button>
    </form>
  );
}

export function MfaVerifyForm() {
  const [state, action, pending] = useActionState(verifyTotpAction, initialFormState);
  return (
    <form action={action} className="grid gap-4" noValidate>
      <FormMessage state={state} />
      <CodeField state={state} />
      <Button type="submit" disabled={pending}>
        {pending ? "Verifying…" : "Verify"}
      </Button>
    </form>
  );
}
